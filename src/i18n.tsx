export function translate(language: Language, text: string): string {
  if (language === 'hu') return text;
  const stepError = /^A\(z\) (\d+)\. lépés(?: formátuma érvénytelen|ből hiányzik a cím, összefoglaló vagy ellenőrzőpont|hez az AI nem készített használható ellenőrzőpontokat)\.$/.exec(text);
  if (stepError) {
    if (text.includes('formátuma érvénytelen')) return `Format von Schritt ${stepError[1]} ist ungültig.`;
    if (text.includes('lépésből hiányzik')) return `Schritt ${stepError[1]} enthält keinen Titel, keine Zusammenfassung oder Prüfpunkte.`;
    return `Für Schritt ${stepError[1]} hat die KI keine brauchbaren Prüfpunkte erstellt.`;
  }
  return german[text] ?? text;
}

export const LanguageContext = createContext<{ language: Language; t: (text: string) => string }>({
  language: 'hu',
  t: (text) => text,
});

export function useTranslation() {
  return useContext(LanguageContext);
}

export function Localized({ children }: { children: ReactNode }) {
  const { language } = useTranslation();
  if (language === 'hu') return children;

  function localize(node: ReactNode): ReactNode {
    if (typeof node === 'string') {
      const whitespace = /^(\s*)(.*?)(\s*)$/.exec(node);
      if (!whitespace) return node;
      return `${whitespace[1]}${translate(language, whitespace[2])}${whitespace[3]}`;
    }
    if (Array.isArray(node)) return Children.map(node, localize);
    if (!isValidElement<{ children?: ReactNode }>(node)) return node;

    const props = { ...node.props } as Record<string, unknown>;
    for (const attribute of ['placeholder', 'aria-label', 'aria-description', 'title', 'alt']) {
      const value = props[attribute];
      if (typeof value === 'string') props[attribute] = translate(language, value);
    }
    if (node.props.children !== undefined) props.children = localize(node.props.children);
    return cloneElement(node, props);
  }

  return <>{localize(children)}</>;
}
